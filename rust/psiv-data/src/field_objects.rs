/// The routine at object id `id`, a `FieldObjectsJmpTbl` byte offset: `None`
/// for an offset that is not a multiple of four or is past the table.
#[must_use]
pub fn field_object_symbol(id: u16) -> Option<&'static str> {
    if !id.is_multiple_of(4) {
        return None;
    }
    FIELD_OBJECT_SYMBOLS.get(usize::from(id / 4)).copied()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_ids_by_jump_table_offset() {
        assert_eq!(field_object_symbol(0x38), Some("NPCType1"));
        assert_eq!(field_object_symbol(0x50), Some("NPCType7"));
        assert_eq!(field_object_symbol(0xA0), Some("TreasureChest"));
        assert_eq!(field_object_symbol(0x3A), None);
        assert_eq!(field_object_symbol(222 * 4), None);
    }
}
