/// Maps whose row is a proxy: an entry event owns the field before the
/// cutscene can fire, so the row is the fixture's own first load of the map,
/// the same routine. On the 27 maps both could measure the two differ by up to
/// two frames (`docs/scenes/FIELD_RELOAD.md`).
static PROXY_MAPS: &[u16] = &[
    // BEGIN GENERATED PROXY
    0x000, 0x001, 0x017, 0x05e, 0x093, 0x098, 0x099, 0x0c0, 0x0c4, 0x0ec, 0x0f0, 0x0f6, 0x0fb,
    0x0fc, 0x14d, 0x171, 0x190,
    // END GENERATED PROXY
];

/// The measured frames `GameMode_LoadFieldMap` spends on `map`, `Pal_FadeIn`
/// included, with the music branch taken or not; `None` for a map the pack
/// does not have.
#[must_use]
pub fn field_reload_rows(map: u16, music_written: bool) -> Option<u16> {
    ROWS.binary_search_by_key(&map, |&(id, _, _)| id)
        .ok()
        .map(|index| {
            let (_, plain, music) = ROWS[index];
            if music_written { music } else { plain }
        })
}

/// Whether `map`'s row is the first-load proxy rather than a cutscene-return
/// measurement.
#[must_use]
pub fn field_reload_is_proxy(map: u16) -> bool {
    PROXY_MAPS.binary_search(&map).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_sorted_and_every_row_includes_the_fade() {
        assert!(ROWS.windows(2).all(|pair| pair[0].0 < pair[1].0));
        assert!(
            ROWS.iter()
                .all(|&(_, plain, music)| plain >= 16 && music >= plain)
        );
        assert!(PROXY_MAPS.windows(2).all(|pair| pair[0] < pair[1]));
        assert!(
            PROXY_MAPS
                .iter()
                .all(|&map| field_reload_rows(map, false).is_some())
        );
        assert!(field_reload_is_proxy(0) && !field_reload_is_proxy(0x14));
    }

    /// The two tape-35 landings and the principal's organic end.
    #[test]
    fn the_organic_anchors_are_in_the_table() {
        // The landings took the music branch (`$9B` to `$89`) and still spent
        // 52 and 42: the frame is absorbed there.
        assert_eq!(field_reload_rows(0x18D, false), Some(52));
        assert_eq!(field_reload_rows(0x18D, true), Some(52));
        assert_eq!(field_reload_rows(0xBF, false), Some(42));
        assert_eq!(field_reload_rows(0xBF, true), Some(42));
        assert_eq!(field_reload_rows(0x14, false), Some(54));
        assert_eq!(field_reload_rows(0x14, true), Some(55));
    }
}
